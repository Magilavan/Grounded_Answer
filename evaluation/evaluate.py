#!/usr/bin/env python3
"""
Run the 10-question evaluation set against the live pipeline and report
honest pass/fail results.

    python evaluation/evaluate.py

Grading rules (deliberately explicit, not just "close enough"):
  - behavior match: the decision type (ANSWER/REFUSE/CONFLICT) must match
    expected_behavior exactly.
  - citation match (only for "answer" and "conflict" cases): every clause
    in expected_clauses must appear among the citations actually returned.
    Extra citations beyond the expected set are not penalised here (see
    RESULTS.md and DECISIONS.md for why the system sometimes returns
    additional, genuinely-related clauses alongside the minimal answer),
    but a MISSING expected citation is a failure.
  - a "refuse" case has no expected_clauses and passes on behavior alone.

This script does not fabricate or adjust results -- whatever the pipeline
actually returns is what gets graded and written to RESULTS.md.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from app.pipeline import PipelineContext, answer_question

QUESTIONS_PATH = Path(__file__).resolve().parent / "questions.json"
RESULTS_PATH = Path(__file__).resolve().parent / "RESULTS.md"


def grade(case: dict, result) -> tuple[bool, str]:
    expected_behavior = case["expected_behavior"]
    actual_behavior = result.decision.decision_type.value.lower()

    if actual_behavior != expected_behavior:
        return False, (
            f"expected behavior '{expected_behavior}', got '{actual_behavior}'"
        )

    expected_clauses = case.get("expected_clauses", [])
    if expected_clauses:
        actual_citations = set(result.generation.citations)
        missing = [c for c in expected_clauses if c not in actual_citations]
        if missing:
            return False, f"missing expected citation(s): {', '.join(missing)}"

    return True, "ok"


def main() -> int:
    cases = json.loads(QUESTIONS_PATH.read_text(encoding="utf-8"))
    ctx = PipelineContext.load()

    rows = []
    for case in cases:
        result = answer_question(case["question"], ctx)
        passed, note = grade(case, result)
        rows.append(
            {
                "id": case["id"],
                "category": case["category"],
                "question": case["question"],
                "expected_behavior": case["expected_behavior"],
                "expected_clauses": case.get("expected_clauses", []),
                "actual_behavior": result.decision.decision_type.value.lower(),
                "actual_citations": result.generation.citations,
                "passed": passed,
                "note": note,
                "answer_text": result.generation.text,
            }
        )

    total = len(rows)
    passed_count = sum(1 for r in rows if r["passed"])

    answer_rows = [r for r in rows if r["expected_behavior"] == "answer"]
    refuse_rows = [r for r in rows if r["expected_behavior"] == "refuse"]
    conflict_rows = [r for r in rows if r["expected_behavior"] == "conflict"]

    def rate(subset):
        if not subset:
            return "n/a"
        return f"{sum(1 for r in subset if r['passed'])}/{len(subset)}"

    citation_checked = [r for r in rows if r["expected_clauses"]]
    citation_correct = sum(
        1
        for r in citation_checked
        if set(r["expected_clauses"]).issubset(set(r["actual_citations"]))
    )

    lines = []
    lines.append("# Evaluation Results\n")
    lines.append(
        "Generated by `python evaluation/evaluate.py` against the live pipeline. "
        "These are the actual results of the actual code in this repository as of "
        "the last run -- nothing here is hand-edited.\n"
    )
    lines.append(f"Total tests: {total}")
    lines.append(f"Passed: {passed_count}")
    lines.append(f"Failed: {total - passed_count}")
    lines.append(f"Pass rate: {passed_count / total * 100:.0f}%\n")
    lines.append(f"Grounded answer accuracy (answer cases): {rate(answer_rows)}")
    lines.append(f"Refusal accuracy (refuse cases): {rate(refuse_rows)}")
    lines.append(f"Conflict handling (conflict cases): {rate(conflict_rows)}")
    lines.append(
        f"Citation accuracy (expected clause present when one was expected): "
        f"{citation_correct}/{len(citation_checked)}\n"
    )

    lines.append("## Per-question results\n")
    lines.append("| ID | Category | Expected | Actual | Result |")
    lines.append("|----|----------|----------|--------|--------|")
    for r in rows:
        mark = "PASS" if r["passed"] else "FAIL"
        lines.append(
            f"| {r['id']} | {r['category']} | {r['expected_behavior']} "
            f"| {r['actual_behavior']} | {mark} |"
        )

    failures = [r for r in rows if not r["passed"]]
    if failures:
        lines.append("\n## Failure detail\n")
        for r in failures:
            lines.append(f"### {r['id']} ({r['category']})\n")
            lines.append(f"**Question:** {r['question']}\n")
            lines.append(
                f"**Expected:** {r['expected_behavior']}"
                + (f", citing {', '.join(r['expected_clauses'])}" if r["expected_clauses"] else "")
            )
            lines.append(
                f"**Actual:** {r['actual_behavior']}"
                + (f", cited {', '.join(r['actual_citations'])}" if r["actual_citations"] else ", no citations")
            )
            lines.append(f"**Why it failed:** {r['note']}\n")

    lines.append("\n## Full transcript\n")
    for r in rows:
        lines.append(f"### {r['id']}: {r['question']}\n")
        lines.append(f"*Decision: {r['actual_behavior'].upper()}*\n")
        lines.append("```")
        lines.append(r["answer_text"])
        lines.append("```\n")

    RESULTS_PATH.write_text("\n".join(lines), encoding="utf-8")

    print(f"{passed_count}/{total} passed. Results written to {RESULTS_PATH}")
    return 0 if passed_count == total else 1


if __name__ == "__main__":
    raise SystemExit(main())
